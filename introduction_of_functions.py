# 1. What is a Function?
# Definition: A function is a block of reusable code that performs a specific task whenever it is called.

# In simple words, a function is a group of statements written together to perform a particular operation. 

# 2. Why do we use Functions?

# Functions are useful because:

# 1. Code Reusability: 
# Write code once and use it multiple times.

# 2. Reduces Code Repetition: 
# Avoid writing the same code again and again.

# 3. Easy to Understand:
#  Divides a large program into smaller parts.

# 4. Easy Debugging:
#  Makes it easier to find and correct errors.

# 5. Modularity: 
# Divides a program into separate functions for different tasks.

