# Input and Output in Python

# Example 1: Printing a message
print("Hello Python")

# Example 2: Printing numbers
print(10 + 20)

# Example 3: Taking a user's name
name = input("Enter your name: ")
print("Hello", name)

# Example 4: Taking an integer as input
age = int(input("Enter your age: "))
print("Your age is", age)

# Example 5: Taking two numbers and adding them
a = int(input("Enter first number: "))
b = int(input("Enter second number: "))
print("Sum =", a + b)

# Example 6: Taking decimal input
price = float(input("Enter the price: "))
print("Price =", price)

# Example 7: Converting a number to a string
number = 100
text = str(number)
print("Number as string:", text)

# Example 8: Displaying multiple values
name = "Gaythri"
age = 22
print("Name:", name, "Age:", age)