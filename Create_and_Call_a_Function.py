# There are two important steps:

# Step 1: Function Definition

def greeting():
    print("Hello Python") 
# Here, we have created a function named greeting.

# Step 2: Function Calling
def greeting():
    print("Hello Python")
greeting()

# Defining a function does not execute its code. The function executes when we call it.

